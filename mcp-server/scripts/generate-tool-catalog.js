import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');
const distToolsDir = path.resolve(__dirname, '..', 'dist', 'tools');
const outputPath = path.resolve(repoRoot, 'docs', 'tool-catalog.md');

const toolModules = [
  { title: 'File Tools', file: 'file-tools.js' },
  { title: 'Scene Tools', file: 'scene-tools.js' },
  { title: 'Editor Scene Tools', file: 'editor-scene-tools.js' },
  { title: 'Editor View Tools', file: 'editor-view-tools.js' },
  { title: 'Layout Tools', file: 'layout-tools.js' },
  { title: 'Lighting Tools', file: 'lighting-tools.js' },
  { title: 'Navigation Tools', file: 'navigation-tools.js' },
  { title: 'Signal Tools', file: 'signal-tools.js' },
  { title: 'Script Tools', file: 'script-tools.js' },
  { title: 'Project Tools', file: 'project-tools.js' },
  { title: 'Asset Tools', file: 'asset-tools.js' },
  { title: 'Visualizer Tools', file: 'visualizer-tools.js' },
  { title: 'Runtime Tools', file: 'runtime-tools.js' },
];

function propertyType(schema) {
  if (!schema) return 'unknown';
  if (schema.oneOf?.length) {
    return schema.oneOf.map(propertyType).join(' | ');
  }
  if (schema.type) return schema.type;
  return 'unknown';
}

function renderProperty(name, schema, requiredSet) {
  const required = requiredSet.has(name) ? 'required' : 'optional';
  const type = propertyType(schema);
  const description = schema?.description ?? '';
  return `- \`${name}\` (${type}, ${required})${description ? `: ${description}` : ''}`;
}

async function loadToolGroup(file) {
  const modulePath = pathToFileURL(path.join(distToolsDir, file)).href;
  const mod = await import(modulePath);
  const exportName = Object.keys(mod).find((key) => Array.isArray(mod[key]));
  if (!exportName) {
    throw new Error(`No tool array export found in ${file}`);
  }
  return mod[exportName];
}

async function main() {
  const groups = [];

  for (const module of toolModules) {
    const tools = await loadToolGroup(module.file);
    groups.push({ title: module.title, tools });
  }

  const totalTools = groups.reduce((sum, group) => sum + group.tools.length, 0);
  const lines = [];

  lines.push('# Tool Catalog');
  lines.push('');
  lines.push(`Generated from the live TypeScript MCP registry. Current total: **${totalTools} tools**.`);
  lines.push('');
  lines.push('This file is generated by `mcp-server/scripts/generate-tool-catalog.js`. Do not hand-edit it.');
  lines.push('');

  for (const group of groups) {
    lines.push(`## ${group.title}`);
    lines.push('');
    for (const tool of group.tools) {
      lines.push(`### \`${tool.name}\``);
      lines.push('');
      lines.push(tool.description);
      lines.push('');

      const properties = tool.inputSchema?.properties ?? {};
      const requiredSet = new Set(tool.inputSchema?.required ?? []);
      const propertyNames = Object.keys(properties);

      if (propertyNames.length === 0) {
        lines.push('No input properties.');
        lines.push('');
        continue;
      }

      for (const propertyName of propertyNames) {
        lines.push(renderProperty(propertyName, properties[propertyName], requiredSet));
      }
      lines.push('');
    }
  }

  mkdirSync(path.dirname(outputPath), { recursive: true });
  while (lines.at(-1) === '') {
    lines.pop();
  }
  writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8');
  console.log(`Wrote ${outputPath}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
